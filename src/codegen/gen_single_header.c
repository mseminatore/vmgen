#include "gen_single_header.h"
#include "emit.h"
#include "../util/buffer.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

static void make_upper(char *dst, const char *src, size_t max) {
    size_t i;
    for (i = 0; i < max - 1 && src[i]; i++)
        dst[i] = (char)toupper((unsigned char)src[i]);
    dst[i] = '\0';
}

/* Read a file into a malloc'd string, stripping include guards and #include "local.h" */
static char *read_and_strip(const char *dir, const char *filename) {
    char path[512];
    snprintf(path, sizeof(path), "%s/%s", dir, filename);

    FILE *fp = fopen(path, "r");
    if (!fp) return NULL;

    fseek(fp, 0, SEEK_END);
    long sz = ftell(fp);
    fseek(fp, 0, SEEK_SET);
    if (sz <= 0) { fclose(fp); return NULL; }

    char *buf = (char *)malloc((size_t)sz + 1);
    if (!buf) { fclose(fp); return NULL; }
    size_t n = fread(buf, 1, (size_t)sz, fp);
    buf[n] = '\0';
    fclose(fp);
    return buf;
}

/* Append file content, skipping #ifndef/#define/#endif guards and local #includes */
static void append_filtered(vmgen_buf_t *out, const char *content, const char *guard) {
    const char *p = content;
    int has_guard = (guard && guard[0] != '\0');
    char guard_ifndef[256] = {0}, guard_define[256] = {0}, guard_endif[256] = {0};
    if (has_guard) {
        snprintf(guard_ifndef, sizeof(guard_ifndef), "#ifndef %s", guard);
        snprintf(guard_define, sizeof(guard_define), "#define %s", guard);
        snprintf(guard_endif, sizeof(guard_endif), "#endif /* %s */", guard);
    }

    while (*p) {
        /* Find end of line */
        const char *eol = strchr(p, '\n');
        if (!eol) eol = p + strlen(p);
        size_t line_len = (size_t)(eol - p);

        /* Skip include guard lines */
        if (has_guard &&
            (strncmp(p, guard_ifndef, strlen(guard_ifndef)) == 0 ||
             strncmp(p, guard_define, strlen(guard_define)) == 0 ||
             strncmp(p, guard_endif, strlen(guard_endif)) == 0)) {
            p = (*eol) ? eol + 1 : eol;
            continue;
        }

        /* Skip local #include "..." lines (but keep <...> includes) */
        if (strncmp(p, "#include \"", 10) == 0) {
            p = (*eol) ? eol + 1 : eol;
            continue;
        }

        /* Skip "DO NOT EDIT" header comment blocks */
        if (strncmp(p, "/*", 2) == 0 && strstr(p, "DO NOT EDIT")) {
            const char *end = strstr(p, "*/");
            if (end) {
                p = end + 2;
                if (*p == '\n') p++;
                continue;
            }
        }

        /* Copy line */
        vmgen_buf_append_len(out, p, line_len);
        if (*eol) vmgen_buf_appendc(out, '\n');
        p = (*eol) ? eol + 1 : eol;
    }
}

int vmgen_gen_single_header(const vmgen_spec_t *spec, const char *output_dir) {
    char upper[VMGEN_MAX_NAME];
    make_upper(upper, spec->name, sizeof(upper));

    char path[512];
    snprintf(path, sizeof(path), "%s/%s.h", output_dir, spec->name);

    vmgen_buf_t buf;
    vmgen_buf_init(&buf);

    char guard[128];
    snprintf(guard, sizeof(guard), "%s_SINGLE_HEADER_H", upper);

    vmgen_buf_appendf(&buf,
        "/*\n"
        " * %s.h — Single-header amalgamation\n"
        " * Generated by vmgen for VM '%s' v%s\n"
        " *\n"
        " * Usage:\n"
        " *   #include \"%s.h\"            // declarations only\n"
        " *\n"
        " * In exactly ONE .c file:\n"
        " *   #define %s_IMPLEMENTATION\n"
        " *   #include \"%s.h\"\n"
        " */\n\n"
        "#ifndef %s\n"
        "#define %s\n\n"
        "#include <stdint.h>\n"
        "#include <stddef.h>\n"
        "#include <stdlib.h>\n"
        "#include <string.h>\n"
        "#include <stdio.h>\n\n",
        spec->name, spec->name, spec->version,
        spec->name, upper, spec->name,
        guard, guard);

    /* Header section: all .h files */
    vmgen_buf_append(&buf,
        "/* ========== DECLARATIONS ========== */\n\n");

    /* Order matters: opcodes first, then gc, strings, closures, vm, etc. */
    const char *headers[] = {
        "opcodes.h", "gc.h", "strings.h", "closures.h",
        "native.h", "modules.h", "fibers.h",
        "vm.h", "assembler.h", "disasm.h", "bytecode.h", "linemap.h", "verify.h", "optimizer.h",
        NULL
    };

    for (int i = 0; headers[i]; i++) {
        char *content = read_and_strip(output_dir, headers[i]);
        if (!content) continue;

        char hguard[128];
        /* Construct guard name: FULLVM_OPCODES_H etc. */
        char base[64];
        strncpy(base, headers[i], sizeof(base) - 1);
        base[sizeof(base) - 1] = '\0';
        /* Replace . with _ and uppercase */
        for (char *c = base; *c; c++) {
            if (*c == '.') *c = '_';
            *c = (char)toupper((unsigned char)*c);
        }
        snprintf(hguard, sizeof(hguard), "%s_%s", upper, base);

        vmgen_buf_appendf(&buf, "/* --- %s --- */\n", headers[i]);
        append_filtered(&buf, content, hguard);
        vmgen_buf_appendc(&buf, '\n');
        free(content);
    }

    /* Implementation section */
    vmgen_buf_appendf(&buf,
        "\n#ifdef %s_IMPLEMENTATION\n\n"
        "/* ========== IMPLEMENTATION ========== */\n\n",
        upper);

    const char *sources[] = {
        "gc.c", "strings.c", "closures.c",
        "native.c", "modules.c", "fibers.c",
        "vm.c", "assembler.c", "disasm.c", "bytecode.c", "linemap.c", "verify.c", "optimizer.c",
        NULL
    };

    for (int i = 0; sources[i]; i++) {
        char *content = read_and_strip(output_dir, sources[i]);
        if (!content) continue;

        vmgen_buf_appendf(&buf, "/* --- %s --- */\n", sources[i]);
        append_filtered(&buf, content, "");
        vmgen_buf_appendc(&buf, '\n');
        free(content);
    }

    vmgen_buf_appendf(&buf,
        "#endif /* %s_IMPLEMENTATION */\n\n"
        "#endif /* %s */\n",
        upper, guard);

    int rc = vmgen_buf_write_file(&buf, path);
    vmgen_buf_free(&buf);
    if (rc == 0) printf("vmgen: generated %s\n", path);
    return rc;
}
